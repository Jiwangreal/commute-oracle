#!/usr/bin/env node
/**
 * 由旁白时长生成视频时间轴：video/timeline.js + video/timeline.json
 * 旁白：video/narration/*.mp3（edge-tts 生成）
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const durations = JSON.parse(fs.readFileSync(path.join(root, 'video/narration/durations.json'), 'utf8'));

const LEAD = 0.8;
const TAIL = 1.6;
const INTRO = 2.6;

const meta = [
  { id: 's1', audio: 's1', base: 6.5 },
  { id: 's2', audio: 's2', base: 10 },
  { id: 's3', audio: 's3', base: 12.8 },
  { id: 's4', audio: 's4', base: 12 },
  { id: 's5', audio: 's5', base: 16 },
  { id: 's6', audio: 's6', base: 11 },
  { id: 's7', audio: 's7', base: 10 },
  { id: 's8', audio: 's8', base: 8 }
];

const scenes = meta.map((m) => {
  const d = durations[m.audio];
  const duration = Math.max(m.base, LEAD + d + TAIL);
  return { ...m, audioDuration: d, duration: Math.round(duration * 10) / 10 };
});

const total = Math.round((INTRO + scenes.reduce((a, s) => a + s.duration, 0)) * 10) / 10;
const timeline = { intro: INTRO, lead: LEAD, total, scenes };

fs.writeFileSync(path.join(root, 'video/timeline.json'), JSON.stringify(timeline, null, 2));
fs.writeFileSync(path.join(root, 'video/timeline.js'),
  '/* generated by scripts/build-video-timeline.mjs */\nwindow.TIMELINE = ' + JSON.stringify(timeline) + ';\n');

console.log(scenes.map((s) => `${s.id}: ${s.duration}s`).join('  '));
console.log('total', total + 's');
